"""The transparency log's Merkle core (carlos-portal#37, inert) against reference vectors.

Three independent anchors, so that the module is not only tested against itself:

1. **The Certificate Transparency reference data set**: eight fixed leaves and the root of every
   prefix of them, one inclusion path (leaf 0 of 8) and three consistency proofs (1 to 8, 6 to 8,
   2 to 5) pinned as constants. These are the well-known `rfc6962` reference values of Google's
   `certificate-transparency` and Trillian, **typed here from memory and then verified by
   independent recomputation** (this module, the recursive reading in point 2, and a second
   reviewer's own algorithm all give the same bytes); they were **not copied from a fetched
   file**, and RFC 6962 and RFC 9162 themselves contain no test vectors. Every other proof in
   this file is generated by the module and then checked by the verifier.
2. **An independent recursive reading of RFC 9162 section 2.1.1** written out in this file (it
   shares no code with the module), compared for every tree size up to 70.
3. **Exhaustive properties** over every leaf of every tree up to 40 entries, and every pair of
   sizes up to 40: each generated proof verifies, and each way of damaging it does not.
"""

